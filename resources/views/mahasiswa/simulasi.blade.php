@push('scripts')
<script>
    const currentIpk = {{ (float) $mahasiswa->ipk }};
    const currentSks = {{ (int) $mahasiswa->total_sks }};
    const currentMutu = currentIpk * currentSks;

    const masterMk = @json($mataKuliahs);

    function getKonversi(angka) {
        if (angka >= 85) return { huruf: 'A', bobot: 4.00 };
        if (angka >= 80) return { huruf: 'A-', bobot: 3.75 };
        if (angka >= 75) return { huruf: 'B+', bobot: 3.50 };
        if (angka >= 70) return { huruf: 'B', bobot: 3.00 };
        if (angka >= 65) return { huruf: 'B-', bobot: 2.75 };
        if (angka >= 60) return { huruf: 'C+', bobot: 2.50 };
        if (angka >= 55) return { huruf: 'C', bobot: 2.00 };
        if (angka >= 40) return { huruf: 'D', bobot: 1.00 };
        return { huruf: 'E', bobot: 0.00 };
    }

    function addRow(nama = '', sks = 3, nilai = 85) {
        const tbody = document.getElementById('simulasiBody');
        const tr = document.createElement('tr');
        tr.className = 'hover:bg-slate-50 transition-all';

        let options = '<option value="">-- Pilih Mata Kuliah --</option>';
        masterMk.forEach(mk => {
            const selected = mk.nama_mk === nama ? 'selected' : '';
            options += `<option value="${mk.nama_mk}" data-sks="${mk.sks}" ${selected}>${mk.kode_mk} - ${mk.nama_mk} (${mk.sks} SKS)</option>`;
        });

        tr.innerHTML = `
            <td class="py-2.5 px-3">
                <select class="w-full text-xs bg-slate-50 border border-slate-300 rounded-lg p-2 focus:ring-1 focus:ring-blue-500 mk-select" onchange="onSelectMk(this)">
                    ${options}
                </select>
            </td>
            <td class="py-2.5 px-3 text-center">
                <input type="number" min="1" max="6" value="${sks}" class="w-16 text-center text-xs bg-slate-50 border border-slate-300 rounded-lg p-2 mk-sks" oninput="calculate()">
            </td>
            <td class="py-2.5 px-3 text-center">
                <input type="number" min="0" max="100" step="1" value="${nilai}" class="w-20 text-center text-xs font-semibold bg-slate-50 border border-slate-300 rounded-lg p-2 mk-nilai" oninput="calculate()">
            </td>
            <td class="py-2.5 px-3 text-center font-bold text-xs mk-huruf text-slate-700">-</td>
            <td class="py-2.5 px-3 text-center font-mono font-semibold text-xs mk-bobot text-slate-700">-</td>
            <td class="py-2.5 px-3 text-center">
                <button type="button" onclick="removeRow(this)" class="text-rose-500 hover:text-rose-700 p-1">
                    <i class="fa-solid fa-trash-can"></i>
                </button>
            </td>
        `;
        tbody.appendChild(tr);
        calculate();
    }

    function onSelectMk(selectEl) {
        const selected = selectEl.options[selectEl.selectedIndex];
        const sks = selected.getAttribute('data-sks');
        if (sks) {
            const tr = selectEl.closest('tr');
            tr.querySelector('.mk-sks').value = sks;
            calculate();
        }
    }

    function removeRow(btn) {
        btn.closest('tr').remove();
        calculate();
    }

    function calculate() {
        const rows = document.querySelectorAll('#simulasiBody tr');
        let newSks = 0;
        let newMutu = 0;

        rows.forEach(r => {
            const sks = parseFloat(r.querySelector('.mk-sks').value) || 0;
            const nilai = parseFloat(r.querySelector('.mk-nilai').value) || 0;
            const konv = getKonversi(nilai);

            r.querySelector('.mk-huruf').textContent = konv.huruf;
            r.querySelector('.mk-bobot').textContent = konv.bobot.toFixed(2);

            newSks += sks;
            newMutu += (sks * konv.bobot);
        });

        const estIps = newSks > 0 ? (newMutu / newSks) : 0;
        const totalSksBaru = currentSks + newSks;
        const totalMutuBaru = currentMutu + newMutu;
        const estIpkBaru = totalSksBaru > 0 ? (totalMutuBaru / totalSksBaru) : currentIpk;
        const selisih = estIpkBaru - currentIpk;

        document.getElementById('resIps').textContent = estIps.toFixed(2);
        document.getElementById('resSks').textContent = `${newSks} SKS Baru Direncanakan`;
        document.getElementById('resIpk').textContent = estIpkBaru.toFixed(2);

        const badge = document.getElementById('deltaBadge');
        const text = document.getElementById('deltaText');

        if (selisih > 0.001) {
            badge.className = 'inline-flex items-center gap-1.5 mt-2 px-2.5 py-1 rounded-full text-xs font-semibold bg-emerald-500/20 text-emerald-300 border border-emerald-500/30';
            text.textContent = `+${selisih.toFixed(2)} Naik dari IPK saat ini`;
        } else if (selisih < -0.001) {
            badge.className = 'inline-flex items-center gap-1.5 mt-2 px-2.5 py-1 rounded-full text-xs font-semibold bg-rose-500/20 text-rose-300 border border-rose-500/30';
            text.textContent = `${selisih.toFixed(2)} Turun dari IPK saat ini`;
        } else {
            badge.className = 'inline-flex items-center gap-1.5 mt-2 px-2.5 py-1 rounded-full text-xs font-semibold bg-slate-800 text-slate-300 border border-slate-700';
            text.textContent = 'Stabil / Belum Ada Perubahan';
        }
    }

    // Inisialisasi 3 baris rencana awal
    window.addEventListener('DOMContentLoaded', () => {
        addRow('Kecerdasan Buatan & Data Mining', 3, 85);
        addRow('Technopreneurship & Kepemimpinan', 2, 88);
        addRow('Pemrograman Web Lanjut', 3, 82);
    });
</script>
